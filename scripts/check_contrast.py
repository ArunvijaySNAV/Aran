#!/usr/bin/env python3
"""Measures WCAG 2.x contrast for every foreground/background pair the design uses and writes docs/CONTRAST.md.
Colours are read from the token files (console tokens.css, bank globals.css), never retyped. Exit 1 if a pair is below its minimum.
Usage: python3 scripts/check_contrast.py"""
import re, sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
FILES = {"console": ROOT / "aran-cloud/cloud/static/css/tokens.css", "bank": ROOT / "bank/app/globals.css"}

def tokens(path):
    t = {}
    for m in re.finditer(r"--([a-z0-9-]+):\s*(#[0-9A-Fa-f]{6}|rgba?\([^)]*\))", path.read_text()):
        t.setdefault(m.group(1), m.group(2))
    return t

def rgb(c, over=None):
    if c.startswith("#"):
        return tuple(int(c[i:i + 2], 16) for i in (1, 3, 5))
    v = [float(x) for x in re.findall(r"[\d.]+", c)]
    if len(v) == 4 and over:
        r, a = v[:3], v[3]
        return tuple(round(a * r[i] + (1 - a) * over[i]) for i in range(3))
    return tuple(v[:3])

def lum(c):
    def f(x):
        x /= 255
        return x / 12.92 if x <= .03928 else ((x + .055) / 1.055) ** 2.4
    r, g, b = map(f, c)
    return .2126 * r + .7152 * g + .0722 * b

def ratio(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + .05) / (lb + .05)

# (label, foreground, background, minimum, where). Names refer to token names; "night-attention" is the Night override.
PAIRS = [
    ("Body text", "ink", "bond", 4.5, "everywhere"), ("Body text on page", "ink", "stock", 4.5, "everywhere"),
    ("Secondary text", "ink-2", "bond", 4.5, "labels, hints, table headers"), ("Secondary text on page", "ink-2", "stock", 4.5, "sub-headings"),
    ("Protected (token chip text)", "seal", "seal-soft", 4.5, "token chips, Valid result"), ("Protected on paper", "seal", "bond", 4.5, "links, verdicts"),
    ("Exposed (raw chip text)", "stamp", "stamp-soft", 4.5, "Reveal chip, stamp"), ("Exposed on paper", "stamp", "bond", 4.5, "stamp text"),
    ("Attention text", "attention", "attention-soft", 4.5, "banners, field errors"), ("Attention on paper", "attention", "bond", 4.5, "field errors"),
    ("Bank green button", "#FFFFFF", "bank", 4.5, "primary buttons, top bar"), ("Bank green on soft", "bank", "bank-soft", 4.5, "badges, done steps"),
    ("Seal button (console)", "#FFFFFF", "seal", 4.5, "console primary buttons"),
    ("Control outline", "rule-strong", "bond", 3.0, "inputs, secondary buttons (non-text, 1.4.11)"),
    ("Hairline rule", "rule", "bond", 1.0, "decorative dividers only (not a control boundary)"),
    ("Night text", "night-text", "night-2", 4.5, "Night panels"), ("Night secondary", "night-dim", "night-2", 4.5, "Night captions, table headers"),
    ("Night token", "night-token", "night-2", 4.5, "token chips on Night"), ("Night token on its chip", "night-token", "night-token-bg@night-2", 4.5, "chip text"),
    ("Night raw", "night-raw", "night-raw-bg", 4.5, "raw chip on Night"), ("Night raw on ground", "night-raw", "night", 4.5, "leak pill"),
    ("Night control outline", "night-dim", "night", 3.0, "Night input and pill outlines"),
    ("Night attention", "#F2C46B", "night", 4.5, "attention text in Night (console override)"),
    ("Night primary button", "night", "night-token", 4.5, "Night buttons"),
    ("Focus ring on paper", "bank", "stock", 3.0, "bank focus outline"), ("Focus ring (console) on paper", "seal", "stock", 3.0, "console focus outline"),
    ("Focus ring on Night", "night-token", "night", 3.0, "Night focus outline"),
]

def main():
    out, bad = [], 0
    out.append("# Contrast\n\nGenerated by `scripts/check_contrast.py` from the token files (`tokens.css`, `globals.css`); WCAG 2.x relative luminance. Text needs 4.5:1 (3:1 for large text), control outlines 3:1.\n")
    for name, path in FILES.items():
        t = tokens(path)
        out.append(f"\n## {name} (`{path.relative_to(ROOT)}`)\n\n| Pair | Foreground | Background | Ratio | Minimum | Used for | Result |\n|---|---|---|---|---|---|---|")
        for label, fg, bg, mn, where in PAIRS:
            def get(n, base=None):
                if "@" in n:
                    n, b = n.split("@"); return rgb(t[n], rgb(t[b]))
                return rgb(n) if n.startswith("#") else rgb(t[n]) if n in t else None
            f, b = get(fg), get(bg)
            if f is None or b is None:
                continue
            r = ratio(f, b); ok = r + 1e-9 >= mn
            if not ok: bad += 1
            hx = lambda c: "#%02X%02X%02X" % tuple(int(x) for x in c)
            out.append(f"| {label} | {hx(f)} | {hx(b)} | {r:.2f}:1 | {mn}:1 | {where} | {'pass' if ok else 'FAIL'} |")
    out.append(f"\n{'All pairs pass.' if not bad else str(bad) + ' pair(s) fail.'}\n")
    (ROOT / "docs/CONTRAST.md").write_text("\n".join(out))
    print("\n".join(out[-30:])); sys.exit(1 if bad else 0)
main()
